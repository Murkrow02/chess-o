"""Build the knowledge base: fetch sources, chunk, embed with bge-m3, store in sqlite-vec.

Re-running is cheap: downloads are cached on disk and embeddings are cached by text hash,
so only new or changed chunks reach the embedding model.
"""

import asyncio
import logging

from ..config import settings
from . import sources, store
from .embed import embed

log = logging.getLogger(__name__)
BATCH = 32


async def _embed_missing(texts: list[str]) -> dict[str, bytes]:
    hashes = [store.text_hash(t) for t in texts]
    have = store.cached_embeddings(list(set(hashes)))
    todo = list({h: t for h, t in zip(hashes, texts) if h not in have}.items())
    for i in range(0, len(todo), BATCH):
        part = todo[i:i + BATCH]
        vectors = await embed([t for _, t in part])
        store.cache_embeddings([(h, v) for (h, _), v in zip(part, vectors)])
        if (i // BATCH) % 10 == 0:
            log.info("embedded %d/%d new chunks", min(i + BATCH, len(todo)), len(todo))
    return store.cached_embeddings(list(set(hashes)))


async def ingest(only: list[str] | None = None, refresh: bool = False) -> dict[str, int]:
    done = {}
    for name, fetch in sources.ALL.items():
        if only and name not in only:
            continue
        docs = await asyncio.to_thread(fetch, refresh)
        texts = [c for d in docs for c in d["chunks"]]
        log.info("%s: %d documents, %d chunks", name, len(docs), len(texts))
        vectors = await _embed_missing(texts)
        for d in docs:
            d["chunks"] = [(h, c, vectors[h]) for c in d["chunks"] if (h := store.text_hash(c)) in vectors]
        done[name] = store.replace_source(name, docs)
    write_attribution()
    return done


def write_attribution() -> None:
    """List what is in the index and under which licence, next to the downloaded files."""
    path = settings.knowledge_dir / "sources" / "ATTRIBUTION.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Knowledge base contents", "",
             "Generated by the ingest. Texts are used under the licences below; links point to the originals.", ""]
    for s in store.sources():
        lines.append(f"- **{s['source']}**: {s['docs']} documents, {s['chunks']} chunks, licence: {s['license']}")
    lines += ["", "Wikipedia and Wikibooks texts: CC BY-SA 4.0, by their respective contributors.",
              "Project Gutenberg books: public domain in the United States."]
    path.write_text("\n".join(lines) + "\n")
